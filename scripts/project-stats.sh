#!/usr/bin/env bash
# Project statistics for docs/how-it-was-built.md, computed from a checkout (no build, no network).
# Usage: scripts/project-stats.sh        Output is Markdown tables headed by the date it was generated.
# Submodules that are not checked out (e.g. the private 7WD one) are listed as "not checked out".
set -eu
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

count() { grep -rhoE "$1" "${@:2}" 2>/dev/null | wc -l | tr -d ' '; }
first=$(git log --reverse --format=%ad --date=short | sed -n 1p)
last=$(git log -1 --format=%ad --date=short)
sessions=$(grep -oE "session [0-9]+" STATUS.md | sed -n 1p | grep -oE "[0-9]+")
rows() { grep -hE '^\| IMP-M[0-9]+-[0-9]+ \|' docs/implementation/registry.md docs/implementation/archive/*.md | sort -u; }
items=$(rows | wc -l | tr -d ' ')
done_items=$(rows | grep -c '| DONE |' || true)

echo "Generated by \`scripts/project-stats.sh\` on $(date +%F) from umbrella commit \`$(git rev-parse --short HEAD)\`."
echo
echo "| Measure | Value | Source |"
echo "|---|---|---|"
echo "| Umbrella commits | $(git rev-list --count HEAD) ($first to $last) | \`git rev-list --count HEAD\` |"
echo "| Latest agent session number | $sessions | \`STATUS.md\` *Last Session Summary* |"
echo "| Work items (IMP-*) | $items, of which $done_items done | register rows in \`registry.md\` and \`archive/\` |"
echo "| ADRs | $(ls docs/decisions/[0-9]*.md | wc -l | tr -d ' ') | \`docs/decisions/\` |"
echo "| Requirements documents | $(grep -cE '^\| \[' docs/requirements/INDEX.md || true) | \`docs/requirements/INDEX.md\` |"
echo "| Requirement IDs defined | $(grep -rhoE '^\| (FR|NFR)-[A-Z]+-[0-9]+ \|' docs/requirements | sort -u | wc -l | tr -d ' ') | table rows that define an ID in \`docs/requirements/\` |"
echo "| Specification files | $(find docs/specs -name '*.md' ! -name INDEX.md | wc -l | tr -d ' ') | \`docs/specs/\`, indexes excluded |"
echo "| Review rounds | $(ls -d docs/reviews/*/ | wc -l | tr -d ' ') | \`docs/reviews/\` |"
echo "| Load-test reports | $(ls loadtest/reports/*.md | grep -vc SUMMARY) | \`loadtest/reports/\` |"
echo
echo "| Repository | Commits | Java test methods | TypeScript tests | Main Java files |"
echo "|---|---|---|---|---|"
for r in turnbase-common turnbase-sdk turnbase-platform turnbase-game-host turnbase-frontend turnbase-game-tictactoe turnbase-game-7wonders-duel; do
  if [ ! -e "$r/.git" ]; then echo "| $r | not checked out | | | |"; continue; fi
  jt=$(grep -rhE '^\s*@(Test|ParameterizedTest|RepeatedTest)\b' --include=*.java "$r" 2>/dev/null | wc -l | tr -d ' ' || true)
  tt=$(grep -rhE '^\s*(it|test)(\.each[^(]*)?\(' --include=*.ts --include=*.tsx --exclude-dir=node_modules "$r" 2>/dev/null | wc -l | tr -d ' ' || true)
  mj=$(find "$r" -path '*/src/main/*' -name '*.java' 2>/dev/null | wc -l | tr -d ' ' || true)
  echo "| $r | $(git -C "$r" rev-list --count HEAD) | $jt | $tt | $mj |"
done
